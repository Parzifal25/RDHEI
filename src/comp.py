def _norm_method(name):
    return str(name).split("(")[0].strip().lower()


# Map normalized runtime-CSV labels (e.g. "CNN-3x3 (v4_patch3)") to the
# method names used for the complexity table rows.
_DISPLAY = {
    "cnn-3x3": "CNN-3x3 (Proposed)",
    "cnn-5x5": "CNN-5x5",
    "cnn-noresidual": "CNN-NoResidual",
    "cnn-noweightedloss": "CNN-NoWeightedLoss",
    "cnn-7x7": "CNN-7x7",
}


def load_runtime_results():

    """
    Read runtime generated by run_anal.py

    Expected columns

        Method
        Mean(ms)
        Std(ms)
        Min(ms)
        Max(ms)
        FPS
    """

    if not os.path.exists(RUNTIME_FILE):

        print(
            "Runtime results not found."
        )

        return {}

    df = pd.read_csv(RUNTIME_FILE)

    runtime = {}

    for _, row in df.iterrows():

        runtime[_DISPLAY.get(_norm_method(row["Method"]), row["Method"])] = float(
            row["Mean(ms)"] if "Mean(ms)" in row.index else row["Mean_ms"]
        )

    return runtime


