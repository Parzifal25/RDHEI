# ==========================================================
# Complexity Analysis
# ==========================================================

def analyze_complexity():

    runtime_results = load_runtime_results()

    rows = []

    # ------------------------------------------------------
    # Classical Predictors
    # ------------------------------------------------------

    for method, values in CLASSICAL.items():

        rows.append({

            "Method": method,

            "Parameters": values["Parameters"],

            "Approx FLOPs": values["Approx FLOPs"],

            "Model Size (MB)": round(
                values["Model Size (MB)"], 4
            ),

            "Memory (MB)": round(
                values["Memory (MB)"], 4
            ),

            "Runtime (ms)": round(
                runtime_results.get(method, np.nan), 4
            )

        })

    # ------------------------------------------------------
    # CNN Predictors
    # ------------------------------------------------------

    variants = build_variants()

    for method, model in variants.items():

        params = get_parameters(model)

        flops = calculate_flops(model)

        model_size = get_model_size_mb(model)

        memory = estimate_memory(model)

        runtime = runtime_results.get(
            method,
            np.nan
        )

        rows.append({

            "Method": method,

            "Parameters": params,

            "Approx FLOPs": flops,

            "Model Size (MB)": round(
                model_size,
                4
            ),

            "Memory (MB)": round(
                memory,
                4
            ),

            "Runtime (ms)": round(
                runtime,
                4
            )

        })

    df = pd.DataFrame(

        rows,

        columns=[

            "Method",

            "Parameters",

            "Approx FLOPs",

            "Model Size (MB)",

            "Memory (MB)",

            "Runtime (ms)"

        ]

    )

    return df


