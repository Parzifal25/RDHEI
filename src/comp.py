# ==========================================================
# Model Size
# ==========================================================

def get_model_size_mb(model):

    """
    Includes both parameters
    and registered buffers
    (BatchNorm running statistics).
    """

    param_size = sum(

        p.nelement() *
        p.element_size()

        for p in model.parameters()

    )

    buffer_size = sum(

        b.nelement() *
        b.element_size()

        for b in model.buffers()

    )

    return (

        param_size +
        buffer_size

    ) / (1024 ** 2)


# ==========================================================
# Memory
# ==========================================================

def estimate_memory(model):

    """
    Approximate inference memory.

    Uses parameter + buffer memory.
    """

    return get_model_size_mb(model)


# ==========================================================
# FLOP Utilities
# ==========================================================

def conv2d_flops(
        layer,
        h,
        w
):

    cin = layer.in_channels

    cout = layer.out_channels

    kh, kw = layer.kernel_size

    hout = math.floor(

        (h + 2 * layer.padding[0] - kh)

        / layer.stride[0]

    ) + 1

    wout = math.floor(

        (w + 2 * layer.padding[1] - kw)

        / layer.stride[1]

    ) + 1

    macs = (

        hout *

        wout *

        cout *

        cin *

        kh *

        kw

    )

    return 2 * macs


def linear_flops(layer):

    macs = (

        layer.in_features *

        layer.out_features

    )

    return 2 * macs


# ==========================================================
# Approximate FLOPs
#
# Preferred
# ---------
# ptflops
#
# Fallback
# --------
# Analytical computation
#
# Approximate FLOPs = 2 × MACs
# ==========================================================

def calculate_flops(model):

    if HAS_PTFLOPS:

        try:

            macs, _ = get_model_complexity_info(

                model,

                (
                    1,
                    model.patch_size,
                    model.patch_size
                ),

                as_strings=False,

                print_per_layer_stat=False,

                verbose=False

            )

            return int(
                2 * macs
            )

        except Exception:

            pass

    patch = model.patch_size

    total = 0

    for module in model.modules():

        if isinstance(
            module,
            nn.Conv2d
        ):

            total += conv2d_flops(

                module,

                patch,

                patch

            )

        elif isinstance(
            module,
            nn.Linear
        ):

            total += linear_flops(
                module
            )

    return int(total)


# ==========================================================
# Human Formatter
# ==========================================================

def human_number(value):

    if value >= 1e9:

        return f"{value/1e9:.3f} G"

    if value >= 1e6:

        return f"{value/1e6:.3f} M"

    if value >= 1e3:

        return f"{value/1e3:.3f} K"

    return str(value)


